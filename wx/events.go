import "C"
import (
	"unsafe"
)

// Event wraps a wxEvent pointer and provides access to base event information.
// All wxWidgets events derive from wxEvent. Use the As*Event conversion
// functions to access type-specific data.
type Event struct {
	ptr unsafe.Pointer
}

// Ptr returns the underlying wxEvent pointer.
func (e *Event) Ptr() unsafe.Pointer {
	return e.ptr
}

// GetEventType returns the event type identifier.
// Compare with event type constants (EVT_BUTTON, EVT_CLOSE_WINDOW, etc.).
func (e *Event) GetEventType() int {
	return int(C.wxEvent_GetEventType(e.ptr))
}

// GetId returns the identifier of the object that generated this event.
func (e *Event) GetId() int {
	return int(C.wxEvent_GetId(e.ptr))
}

// GetTimestamp returns the timestamp of the event in milliseconds.
func (e *Event) GetTimestamp() int {
	return int(C.wxEvent_GetTimestamp(e.ptr))
}

// GetEventObject returns a pointer to the object that generated this event.
func (e *Event) GetEventObject() unsafe.Pointer {
	return C.wxEvent_GetEventObject(e.ptr)
}

// IsCommandEvent returns true if this is a command event.
// Command events propagate up through the window hierarchy.
func (e *Event) IsCommandEvent() bool {
	return C.wxEvent_IsCommandEvent(e.ptr) != 0
}

// GetSkipped returns true if Skip() was called on this event.
func (e *Event) GetSkipped() bool {
	return C.wxEvent_GetSkipped(e.ptr) != 0
}

// Skip marks the event as not fully handled, allowing it to propagate
// to the next handler in the chain. Call this when you want the default
// behavior to also occur after your handler runs.
//
// Example — allow default close behavior after logging:
//
//	frame.Bind(wx.EVT_CLOSE_WINDOW, func(evt *wx.Event) {
//	    fmt.Println("Window closing...")
//	    evt.Skip() // Let wxWidgets handle the actual close
//	})
func (e *Event) Skip() {
	C.wxEvent_Skip(e.ptr)
}

// Bind connects an event handler to this window for the given event type.
// The handler will be called whenever an event of the specified type
// is generated by this window (or propagated to it for command events).
//
// Common event types:
//   - EVT_BUTTON — Button click
//   - EVT_TEXT — Text control change
//   - EVT_MENU — Menu item selection
//   - EVT_CLOSE_WINDOW — Window close request
//   - EVT_SIZE — Window resize
//
// Example:
//
//	button.Bind(wx.EVT_BUTTON, func(evt *wx.Event) {
//	    fmt.Println("Button clicked!")
//	})
func (w *BaseWindow) Bind(eventType int, handler EventHandler) {
	id := registerCallback(handler)
	C.goConnectEvent(w.ptr, C.int(-1), C.int(-1), C.int(eventType), C.uintptr_t(id))
}

// BindId connects an event handler for events from a specific control ID.
// Use this to handle events from menu items or when multiple controls of
// the same type need different handlers.
//
// Example:
//
//	frame.BindId(wx.EVT_MENU, wx.ID_EXIT, func(evt *wx.Event) {
//	    frame.Close(false)
//	})
//
//	frame.BindId(wx.EVT_MENU, wx.ID_ABOUT, func(evt *wx.Event) {
//	    wx.MessageBox("About this app", "About", wx.OK|wx.ICON_INFORMATION, frame)
//	})
func (w *BaseWindow) BindId(eventType int, id int, handler EventHandler) {
	cbID := registerCallback(handler)
	C.goConnectEvent(w.ptr, C.int(id), C.int(id), C.int(eventType), C.uintptr_t(cbID))
}

// BindIdRange connects an event handler for events from a range of control IDs.
// This is useful for handling a group of related controls (e.g., a range of
// menu items) with a single handler.
func (w *BaseWindow) BindIdRange(eventType int, firstId, lastId int, handler EventHandler) {
	cbID := registerCallback(handler)
	C.goConnectEvent(w.ptr, C.int(firstId), C.int(lastId), C.int(eventType), C.uintptr_t(cbID))
}

// Unbind disconnects all handlers for the given event type from this window.
func (w *BaseWindow) Unbind(eventType int) {
	C.wxEvtHandler_Disconnect(w.ptr, C.int(-1), C.int(-1), C.int(eventType), nil)
}

// UnbindId disconnects handlers for the given event type and control ID.
func (w *BaseWindow) UnbindId(eventType int, id int) {
	C.wxEvtHandler_Disconnect(w.ptr, C.int(id), C.int(id), C.int(eventType), nil)
}
